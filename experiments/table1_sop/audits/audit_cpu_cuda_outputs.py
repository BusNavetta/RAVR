from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np

from benchmark_nested_additive_ravr import DEFAULT_TARGET_LENGTHS

# The panel this audit reads lives one level up, in the experiment folder.
HERE = Path(__file__).resolve().parents[1]


METRICS = ("teacher_recall_at_10", "teacher_ndcg_at_10")


def audit(
    factory: str,
    seeds: tuple[int, ...],
    targets: tuple[int, ...],
    cpu_calibration: int,
    cuda_calibration: int,
) -> dict:
    output = HERE / "outputs" / "nested_additive_ravr_sop_100k"
    rows = []
    cuda_reports = []
    for target in targets:
        per_metric = {metric: [] for metric in METRICS}
        changed = {metric: 0 for metric in METRICS}
        cpu_seconds, cuda_seconds = [], []
        total = 0
        for seed in seeds:
            stem = f"{factory.lower()}_seed{seed}_test_u{target}_cal"
            cpu = json.loads(
                (output / f"{stem}{cpu_calibration}.json").read_text(encoding="utf-8")
            )
            cuda = json.loads(
                (output / f"{stem}{cuda_calibration}.json").read_text(encoding="utf-8")
            )
            if cpu["source_bundle_sha256"] != cuda["source_bundle_sha256"]:
                raise ValueError(f"seed {seed}, target {target}: source codecs differ")
            if cuda.get("compute_backend", {}).get("resolved") != "cuda":
                raise ValueError(f"seed {seed}, target {target}: CUDA row not recorded")
            cuda_reports.append(cuda["compute_backend"])
            cpu_seconds.append(float(cpu["rows"]["uniform"]["evaluation_seconds"]))
            cuda_seconds.append(float(cuda["rows"]["uniform"]["evaluation_seconds"]))
            for metric in METRICS:
                cpu_values = np.asarray(cpu["rows"]["uniform"]["per_query"][metric])
                cuda_values = np.asarray(cuda["rows"]["uniform"]["per_query"][metric])
                delta = cuda_values - cpu_values
                per_metric[metric].append(delta)
                changed[metric] += int(np.count_nonzero(delta))
                total += len(delta) if metric == METRICS[0] else 0
        for metric in METRICS:
            delta = np.concatenate(per_metric[metric])
            rows.append({
                "target_length": target,
                "metric": metric,
                "cuda_minus_legacy_cpu": float(np.mean(delta)),
                "mean_absolute_per_query_difference": float(np.mean(np.abs(delta))),
                "max_absolute_per_query_difference": float(np.max(np.abs(delta))),
                "changed_queries": changed[metric],
                "query_seed_pairs": total,
                "mean_legacy_cpu_evaluation_seconds": float(np.mean(cpu_seconds)),
                "mean_cuda_evaluation_seconds": float(np.mean(cuda_seconds)),
                "evaluation_speedup": float(
                    np.mean(cpu_seconds) / np.mean(cuda_seconds)
                ),
            })
    versions = {
        json.dumps(report, sort_keys=True) for report in cuda_reports
    }
    if len(versions) != 1:
        raise ValueError("CUDA rows were produced by different recorded backends")
    result = {
        "purpose": (
            "Numerical-backend audit only; it compares uniform allocations with "
            "identical frozen codecs and must not be interpreted as a method effect."
        ),
        "factory": factory,
        "seeds": list(seeds),
        "targets": list(targets),
        "legacy_cpu_source_calibration_queries": cpu_calibration,
        "cuda_source_calibration_queries": cuda_calibration,
        "cuda_backend": json.loads(next(iter(versions))),
        "rows": rows,
    }
    stem = output / f"cpu_cuda_uniform_audit_{factory.lower()}_{len(seeds)}seeds"
    stem.with_suffix(".json").write_text(
        json.dumps(result, indent=2, sort_keys=True), encoding="utf-8"
    )
    stem.with_suffix(".md").write_text(render_markdown(result), encoding="utf-8")
    return result


def render_markdown(report: dict) -> str:
    lines = [
        "# CPU/CUDA exact-scan output audit",
        "",
        report["purpose"],
        "",
        f"CUDA device: `{report['cuda_backend']['device']}`; TF32 disabled. Legacy "
        "files predate backend metadata and were generated by the NumPy CPU path.",
        "",
        "| Target | Metric | CUDA - CPU | Mean absolute per-query diff. | Max absolute diff. | Changed query-seed pairs | CUDA speedup |",
        "|---:|---|---:|---:|---:|---:|---:|",
    ]
    for row in report["rows"]:
        lines.append(
            f"| {row['target_length']} | {row['metric']} | "
            f"{row['cuda_minus_legacy_cpu']:+.7f} | "
            f"{row['mean_absolute_per_query_difference']:.7f} | "
            f"{row['max_absolute_per_query_difference']:.7f} | "
            f"{row['changed_queries']}/{row['query_seed_pairs']} | "
            f"{row['evaluation_speedup']:.2f}x |"
        )
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--factory", default="LSQ16x4")
    parser.add_argument("--seeds", nargs="+", type=int, default=[42, 73, 3067, 4294, 4996, 5423, 7520, 7937, 9794])
    parser.add_argument("--targets", nargs="+", type=int, default=list(DEFAULT_TARGET_LENGTHS))
    parser.add_argument("--cpu-calibration", type=int, default=5000)
    parser.add_argument("--cuda-calibration", type=int, default=400)
    args = parser.parse_args()
    print(render_markdown(audit(
        args.factory,
        tuple(args.seeds),
        tuple(args.targets),
        args.cpu_calibration,
        args.cuda_calibration,
    )))


if __name__ == "__main__":
    main()
